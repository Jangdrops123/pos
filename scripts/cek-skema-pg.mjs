// Validasi struktural pg-migrations/001_skema_pg.sql tanpa server PG.
// Jalankan: node scripts/cek-skema-pg.mjs
import fs from 'node:fs';

const mentah = fs.readFileSync('pg-migrations/001_skema_pg.sql', 'utf8');
// Abaikan komentar baris (-- ...) saat memindai sisa dialek SQLite.
const sql = mentah.replace(/^--.*$/gm, '');
let gagal = 0;
const cek = (nama, kond) => {
  console.log(`${kond ? 'OK  ' : 'GAGAL'} ${nama}`);
  if (!kond) gagal++;
};

const hitung = (re) => (sql.match(re) ?? []).length;
console.log(`AUTOINCREMENT: ${hitung(/AUTOINCREMENT/gi)}`);
console.log(`strftime: ${hitung(/strftime/gi)}`);
console.log(`RAISE(ABORT: ${hitung(/RAISE\(ABORT/gi)}`);
console.log(`PRAGMA: ${hitung(/PRAGMA/gi)}`);
console.log(`COLLATE: ${hitung(/COLLATE/gi)}`);
cek('tanpa sisa dialek SQLite', /AUTOINCREMENT|strftime|RAISE\(ABORT|PRAGMA|COLLATE/i.test(sql) === false);

const defs = [...sql.matchAll(/CREATE TABLE (\w+)/g)].map((m) => m[1]);
const refs = [...sql.matchAll(/REFERENCES (\w+)\(/g)].map((m) => m[1]);
const hilang = [...new Set(refs.filter((r) => !defs.includes(r)))];
cek(`72 tabel (dapat ${defs.length})`, defs.length === 72);
cek(`semua target REFERENCES ada (${hilang.join(',') || 'tidak ada yang hilang'})`, hilang.length === 0);

let d = 0;
for (const ch of sql) { if (ch === '(') d++; if (ch === ')') d--; }
cek('kurung seimbang', d === 0);

cek('ada CREATE EXTENSION citext', sql.includes('CREATE EXTENSION IF NOT EXISTS citext'));
cek('ada BOOLEAN', sql.includes('BOOLEAN'));
cek('ada JSONB', sql.includes('JSONB'));
cek('ada TIMESTAMPTZ', sql.includes('TIMESTAMPTZ'));
cek('ada IDENTITY', sql.includes('GENERATED BY DEFAULT AS IDENTITY'));
cek('ada PRIMARY KEY komposit', sql.includes('PRIMARY KEY (user_id, kartu_id)'));
cek('document_counters kunci PK teks', sql.includes('kunci TEXT PRIMARY KEY'));

process.exit(gagal ? 1 : 0);
